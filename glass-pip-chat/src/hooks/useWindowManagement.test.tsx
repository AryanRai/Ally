import { act, cleanup, renderHook, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { useWindowManagement } from './useWindowManagement';
afterEach(() => { cleanup(); localStorage.clear(); vi.restoreAllMocks(); });
it('keeps independent manual dimensions across modes and reloads, and resets to presets deliberately', async () => {
  localStorage.clear();
  let resized = (_size: { width: number; height: number }) => {};
  const unsubscribe = vi.fn();
  window.pip = { getPlatform: async () => 'win32', getTheme: async () => 'dark', onThemeChanged: () => () => {}, onManualResize: (callback: typeof resized) => { resized = callback; return unsubscribe; } } as any;
  const { result, unmount } = renderHook(() => useWindowManagement());
  await waitFor(() => expect(result.current.platform).toBe('win32'));
  act(() => resized({ width: 310, height: 900 }));
  expect(result.current.manualSize).toEqual({ width: 310, height: 900 });
  act(() => result.current.handleCollapseToggle());
  expect(result.current.manualSize).toBeUndefined();
  act(() => resized({ width: 290, height: 240 }));
  act(() => result.current.handleCollapseToggle());
  expect(result.current.manualSize).toEqual({ width: 310, height: 900 });
  act(() => resized({ width: NaN, height: 10 }));
  expect(result.current.manualSize?.height).toBe(900);
  unmount(); expect(unsubscribe).toHaveBeenCalled();
  const second = renderHook(() => useWindowManagement());
  await waitFor(() => expect(second.result.current.platform).toBe('win32'));
  expect(second.result.current.manualSize).toEqual({ width: 310, height: 900 });
  act(() => second.result.current.handleSizeChange());
  expect(second.result.current.manualSize).toBeUndefined();
  act(() => second.result.current.handleCollapseToggle());
  expect(second.result.current.manualSize).toEqual({ width: 290, height: 240 });
});
